#!/usr/bin/env node
/**
 * Copies MapLibre GL JS (the renderer inside the WebView map, src/components/RouteMap.tsx) from
 * node_modules into src/components/map/vendor/maplibreGl.ts as string constants. The app then
 * ships the library itself: the map page loads nothing from a CDN, only map data from the tile
 * server. Run it after changing the maplibre-gl devDependency:
 *
 *   npm run vendor:maplibre
 *
 * maplibre-gl stays on 5.x on purpose: it is the last major version with a single-file build
 * (worker included), which can be inlined into one HTML page.
 */
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const packageDir = path.join(root, 'node_modules', 'maplibre-gl');
const { version } = JSON.parse(fs.readFileSync(path.join(packageDir, 'package.json'), 'utf8'));
const js = fs.readFileSync(path.join(packageDir, 'dist', 'maplibre-gl.js'), 'utf8');
const css = fs.readFileSync(path.join(packageDir, 'dist', 'maplibre-gl.css'), 'utf8');

// Escape sequences are built from character codes so this file stays plain ASCII.
const BACKSLASH = String.fromCharCode(92);
const LINE_SEPARATOR = String.fromCharCode(0x2028);
const PARAGRAPH_SEPARATOR = String.fromCharCode(0x2029);

// The code goes into inline <script>/<style> elements: a literal closing tag inside it would end
// the element early. A backslash before the slash leaves the JavaScript string unchanged.
const inlineSafeJs = js.split('</script').join(`<${BACKSLASH}/script`);
if (inlineSafeJs.includes('<!--') || css.toLowerCase().includes('</style')) {
  throw new Error('maplibre-gl contains markup that cannot be inlined safely; review scripts/vendor-maplibre.js.');
}

// JSON string literals are valid JavaScript; escape the two line separators older parsers reject.
const literal = (value) =>
  JSON.stringify(value)
    .split(LINE_SEPARATOR)
    .join(`${BACKSLASH}u2028`)
    .split(PARAGRAPH_SEPARATOR)
    .join(`${BACKSLASH}u2029`);

const output = `// Generated by scripts/vendor-maplibre.js from maplibre-gl@${version}. Do not edit by hand.
// MapLibre GL JS is BSD-3-Clause licensed: https://github.com/maplibre/maplibre-gl-js/blob/v${version}/LICENSE.txt
/* eslint-disable */
export const MAPLIBRE_GL_VERSION = ${JSON.stringify(version)};
export const MAPLIBRE_GL_JS = ${literal(inlineSafeJs)};
export const MAPLIBRE_GL_CSS = ${literal(css)};
`;

const target = path.join(root, 'src', 'components', 'map', 'vendor', 'maplibreGl.ts');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, output);
console.log(`Wrote ${path.relative(root, target)} (maplibre-gl ${version}, ${(output.length / 1e6).toFixed(2)} MB)`);
